const vectors = CASES.map((c) => ({
    ...c,
    stringToSign: stringToSign(c),
    expectedSignature: sign(c),
}));

// C++ string literal escaping, so the generated .inc compiles as-is.
function cxx(s) {
    return `"${s
        .replace(/\\/g, "\\\\")
        .replace(/"/g, '\\"')
        .replace(/\n/g, "\\n")}"`;
}

const emitCxx = process.argv.includes("--cxx");

if (emitCxx) {
    const rows = vectors
        .map(
            (v) =>
                `    {${cxx(v.name)}, ${cxx(v.method)}, ${cxx(v.url)}, ${cxx(v.token)},\n` +
                `     ${cxx(v.tmDate)}, ${cxx(v.apiKey)},\n` +
                `     ${cxx(v.stringToSign)},\n` +
                `     ${cxx(v.expectedSignature)}},`,
        )
        .join("\n");

    console.log(`// GENERATED by test/gen-vectors.mjs --cxx -- do not edit by hand.
// Regenerate with:  node test/gen-vectors.mjs --cxx > test/signer-vectors.inc
// These pin our signer against vex-tm-client v1.5.3, the reference implementation.
// A diff here means either upstream changed the algorithm or we introduced a bug.

// clang-format off
static const SignerVector kSignerVectors[] = {
${rows}
};
// clang-format on`);
} else {
    console.log(JSON.stringify({ vectors }, null, 2));
}
